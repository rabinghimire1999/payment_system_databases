"""
API Key schema module.

Defines Pydantic models for API key validation and responses.
"""
from typing import Optional
from uuid import UUID
from datetime import datetime
from pydantic import BaseModel, ConfigDict


class ApiKeyBase(BaseModel):
    """
    Base properties for an API key.

    Attributes:
        fps_id (int): The ID of the fps owning the key.
        is_active (bool): Whether the key is active.
    """
    fps_id: int
    is_active: Optional[bool] = True


class ApiKeyCreate(ApiKeyBase):
    """
    Schema for creating a new API key.
    The actual key will be generated by the system and returned once.

    Attributes:
        fps_id (int): The ID of the fps owning the key.
        is_active (bool): Whether the key should be active upon creation.
    """
    pass


class ApiKeyUpdate(BaseModel):
    """
    Schema for updating an existing API key (e.g., revoking it).

    Attributes:
        is_active (bool): The new active status for the key.
    """
    is_active: Optional[bool] = None


class ApiKeyResponse(ApiKeyBase):
    """
    Response schema for an API key.
    Includes metadata but NOT the secret key itself (only its presence).

    Attributes:
        id (UUID): Unique identifier for the API key.
        created_at (datetime): Timestamp when the key was created.
    """
    id: UUID
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ApiKeyNewResponse(ApiKeyResponse):
    """
    Special response schema for when a new key is generated.
    This is the ONLY time the plain_text_key is visible.

    Attributes:
        plain_text_key (str): The unhashed API key, shown only once.
    """
    plain_text_key: str
